"""Evaluation harness for Bolo Form.

    python -m eval.run_eval --dry-run          # show how many API calls a live run needs
    python -m eval.run_eval                     # run on the configured PROVIDER (default: mock)
    python -m eval.run_eval --provider gnani --conditions clean,phone --n 20

What it measures: the WHOLE dialogue (recognition + parsing + confirmation policy), not just STT.
Policies compared: never_confirm, always_confirm, adaptive.

HONESTY NOTES (also written into the report):
* On the MOCK provider the recognition errors are SIMULATED. Those numbers test the plumbing only
  and say NOTHING about Gnani. results.json is marked "simulated": true.
* On a real provider, test speech is generated by Timbre, which is cleaner than real human speech.
* The simulated user always notices a wrong read-back and always understands yes/no.
* Thresholds are fixed defaults. Tune on --split dev only; report --split test.
"""
