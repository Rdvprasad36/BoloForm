LANDS = [1.0, 1.5, 2.0, 2.5, 3.0, 4.0, 5.0, 7.5, 10.0]

_CANON_UNIT = {v: k for k, v in reversed(list(L.UNITS.items())) if not k.isascii()}
_CANON_TEEN = {v: k for k, v in reversed(list(L.TEENS.items())) if not k.isascii()}
_CANON_TEN = {v: k for k, v in reversed(list(L.TENS.items())) if not k.isascii()}
_HALF = {v: k for k, v in L.HALF_FORMS.items() if v in (1.5, 2.5, 3.5, 4.5, 5.5, 6.5, 7.5)}


def int_to_te(n: int) -> str:
    """1..99 in Telugu words (canonical spellings)."""
    if n < 10:
        return _CANON_UNIT[n]
    if n < 20:
        return _CANON_TEEN[n]
    tens, unit = (n // 10) * 10, n % 10
    return _CANON_TEN[tens] + (f" {_CANON_UNIT[unit]}" if unit else "")


@dataclass
class Persona:
    id: int
    truth: dict
    utt: dict
    typed: dict


def build_personas(form: FormDef, n: int, seed: int) -> list[Persona]:
    rng = random.Random(seed)
    district_choices = next(f for f in form.fields if f.key == "district").choices
    crop_choices = next(f for f in form.fields if f.key == "crop").choices
    out = []
    for i in range(n):
        name, village = rng.choice(NAMES), rng.choice(VILLAGES)
        age = rng.randint(25, 85)
        district = rng.choice(district_choices)
        phone = str(rng.choice("6789")) + "".join(rng.choice("0123456789") for _ in range(9))
        land = rng.choice(LANDS)
        crop = rng.choice(crop_choices)
        bank = rng.random() < 0.7
        words = rng.random() < 0.5
        land_utt = (_HALF.get(land) if (words and land in _HALF)
                    else (int_to_te(int(land)) if words and land.is_integer() and land < 20 else None))
        land_utt = f"{land_utt} ఎకరాలు" if land_utt else f"{land:g} ఎకరాలు"
        phone_utt = (" ".join(_CANON_UNIT[int(c)] for c in phone) if rng.random() < 0.5 else phone)
        truth = {"name": name, "age": age, "village": village, "district": district.value,
                 "phone": phone, "land_acres": land, "crop": crop.value, "has_bank": bank}
        utt = {"name": rng.choice([f"నా పేరు {name}", name]),
               "age": f"{int_to_te(age)}" if words else str(age),
               "village": village, "district": district.te, "phone": phone_utt,
               "land_acres": land_utt, "crop": crop.te, "has_bank": L.YES_TE if bank else "లేదు"}
        typed = {"name": name, "age": str(age), "village": village, "district": district.te,
                 "phone": phone, "land_acres": f"{land:g}", "crop": crop.te,
                 "has_bank": L.YES_TE if bank else L.NO_TE}
        out.append(Persona(i, truth, utt, typed))
    return out


def same(truth, value) -> bool:
    if isinstance(truth, str) and isinstance(value, str):
        return normalize(truth) == normalize(value)
    return truth == value


# ------------------------------------------------------------------ recognition round trips
class MockRT:
    simulated = True

    def __init__(self, seed: int):
        from app.providers.mock import MockProvider
        self.p, self.seed, self.cache = MockProvider(), seed, {}

    def __call__(self, persona: Persona, key: str, cond: str, attempt: int):
        k = (persona.id, key, cond, attempt)
        if k not in self.cache:
            rng = random.Random(f"{self.seed}-{persona.id}-{key}-{cond}-{attempt}")
            r = self.p.mock_roundtrip(persona.utt[key], cond, rng)
            self.cache[k] = (r.text, r.confidence, SNR_MAP[cond])
        return self.cache[k]


class RealRT:
    """Timbre speech -> degrade -> Prisma. Cached so the three policies share the same audio results."""
    simulated = False

    def __init__(self, provider, seed: int):
        import numpy as np
        self.np, self.p, self.seed = np, provider, seed
        self.tts_cache: dict[str, bytes] = {}
        self.cache: dict = {}
        self.calls = {"tts": 0, "stt": 0}

    def _speech(self, text: str) -> bytes:
        if text not in self.tts_cache:
            r = self.p.synthesize(text, "te")
            self.calls["tts"] += 1
            if not r.audio[:4] == b"RIFF":
                raise SystemExit("TTS did not return WAV audio (got %s). Decode it to 16-bit PCM WAV "
                                 "before degrading; see docs/gnani_api_notes.md." % r.mime)
            self.tts_cache[text] = r.audio
        return self.tts_cache[text]

    def __call__(self, persona: Persona, key: str, cond: str, attempt: int):
        from app.audio.degrade import apply_condition
        from app.core.noise_estimate import estimate_snr_db
        k = (persona.id, key, cond, attempt)
        if k not in self.cache:
            h = int(hashlib.sha256(f"{self.seed}-{k}".encode()).hexdigest()[:8], 16)
            wav = apply_condition(self._speech(persona.utt[key]), cond, self.np.random.default_rng(h))
            snr = estimate_snr_db(wav)
            r = self.p.transcribe(wav, "te")
            self.calls["stt"] += 1
            self.cache[k] = (r.text, r.confidence, snr)
        return self.cache[k]


# ------------------------------------------------------------------ one simulated session
def run_form(form: FormDef, persona: Persona, cond: str, policy: str, rt) -> tuple[list[dict], int, int]:
    eng = DialogueEngine(policy)
    s = SessionStore().create(form)
    eng.start(s)
    turns, confirms = 1, 0
    attempts: dict[str, int] = {}
    first: dict[str, dict] = {}
    typed: set[str] = set()
    caught: set[str] = set()
    guard = 0
    while s.state == "ask" and guard < 200:
        guard += 1
        f = s.field_def
        attempt = attempts.get(f.key, 0)
        attempts[f.key] = attempt + 1
        text, conf, snr = rt(persona, f.key, cond, attempt)
        t = eng.handle_utterance(s, text, conf, snr)
        turns += 1
        if attempt == 0:
            val = s.pending.parsed.value if t["action"] == "confirm" and s.pending else s.fields[f.key].value
            first[f.key] = {"heard": text, "value": val}
        if t["action"] == "confirm" and s.pending:
            ok = same(persona.truth[f.key], s.pending.parsed.value)
            t = eng.handle_utterance(s, L.YES_TE if ok else L.NO_TE)
            turns += 1
            confirms += 1
            if not ok and attempt == 0:
                caught.add(f.key)
        if t["action"] == "fallback":
            t = eng.handle_typed(s, persona.typed[f.key])
            turns += 1
            typed.add(f.key)
    rows = []
    for f in form.fields:
        st = s.fields[f.key]
        truth = persona.truth[f.key]
        final_ok = same(truth, st.value)
        fv = first.get(f.key, {}).get("value")
        rows.append({
            "key": f.key, "first_ok": same(truth, fv), "final_ok": final_ok,
            "silent": (not final_ok) and st.status in ("implicit", "confirmed"),
            "caught": f.key in caught and final_ok and f.key not in typed,
            "typed": f.key in typed, "status": st.status,
            "truth": truth, "got": st.value, "heard": first.get(f.key, {}).get("heard"),
        })
    return rows, turns, confirms


def wilson(k: int, n: int, z: float = 1.96) -> list[float]:
    if n == 0:
        return [0.0, 0.0]
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    a = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return [round(max(0.0, (c - a) / d), 4), round(min(1.0, (c + a) / d), 4)]


def summarize(forms_rows: list[tuple[list[dict], int, int]]) -> dict:
    rows = [r for fr, _, _ in forms_rows for r in fr]
    n = len(rows)
    cnt = lambda key: sum(1 for r in rows if r[key])          # noqa: E731
    out = {"n_forms": len(forms_rows), "n_fields": n,
           "turns_per_form": round(sum(t for _, t, _ in forms_rows) / len(forms_rows), 2),
           "confirms_per_form": round(sum(c for _, _, c in forms_rows) / len(forms_rows), 2),
           "errors_caught": cnt("caught")}
    for name, key in (("first_pass_acc", "first_ok"), ("final_acc", "final_ok"),
                      ("silent_error_rate", "silent"), ("typed_fallback_rate", "typed")):
        k = cnt(key)
        out[name] = round(k / n, 4)
        out[name + "_ci95"] = wilson(k, n)
    return out


# ------------------------------------------------------------------ main
def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--provider", default=None, help="mock | gnani (default: PROVIDER env or mock)")
    ap.add_argument("--n", type=int, default=40, help="personas (half dev, half test)")
    ap.add_argument("--split", default="test", choices=["dev", "test", "all"])
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--conditions", default="clean,noise20,noise10,noise5,phone")
    ap.add_argument("--max-calls", type=int, default=1500, help="refuse to run a live eval above this many calls")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--out", default=str(RESULTS_DIR))
    a = ap.parse_args(argv)

    from app.config import Settings
    settings = Settings.load()
    pname = (a.provider or settings.provider).lower()
    conds = [c.strip() for c in a.conditions.split(",") if c.strip()]
    form = load_forms(ROOT / "app" / "forms")["farmer_scheme"]
    personas = build_personas(form, a.n, a.seed)
    half = len(personas) // 2
    split = {"dev": personas[:half], "test": personas[half:], "all": personas}[a.split]

    n_fields = len(form.fields)
    est_tts, est_stt = len(split) * n_fields, len(split) * n_fields * len(conds)
    print(f"provider={pname} split={a.split} personas={len(split)} conditions={conds}")
    print(f"live-call estimate (lower bound, re-asks add more): TTS ~{est_tts}, STT ~{est_stt}")
    if a.dry_run:
        print("dry run: nothing executed." + (" (mock provider uses no credits)" if pname == "mock" else ""))
        return 0

    if pname == "gnani":
        if est_tts + est_stt > a.max_calls:
            print(f"Refusing: {est_tts + est_stt} calls exceeds --max-calls {a.max_calls}. "
                  "Reduce --n or --conditions, and keep a credit reserve for the live demo.")
            return 2
        from app.providers.gnani import GnaniProvider
        rt = RealRT(GnaniProvider(), a.seed)
    else:
        rt = MockRT(a.seed)

    results: dict = {}
    worst: list[dict] = []
    t0 = time.time()
    for cond in conds:
        results[cond] = {}
        for pol_name, pol in POLICIES.items():
            runs = [run_form(form, p, cond, pol, rt) for p in split]
            results[cond][pol_name] = summarize(runs)
            if pol_name == "adaptive":
                for rows, _, _ in runs:
                    for r in rows:
                        if not r["final_ok"] and len(worst) < 15:
                            worst.append({"condition": cond, "policy": pol_name, **{k: r[k] for k in
                                          ("key", "truth", "got", "heard", "status", "silent")}})
    meta = {"provider": pname, "simulated": bool(rt.simulated), "split": a.split, "seed": a.seed,
            "personas": len(split), "conditions": conds, "policies": list(POLICIES),
            "generated_at": time.strftime("%Y-%m-%d %H:%M:%S"), "seconds": round(time.time() - t0, 1),
            "live_calls": getattr(rt, "calls", None)}
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    payload = {"meta": meta, "results": results, "worst_adaptive_failures": worst}
    (out / "results.json").write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    (out / "report.md").write_text(render_report(payload), encoding="utf-8")
    print(f"wrote {out / 'results.json'} and {out / 'report.md'}")
    return 0


def render_report(p: dict) -> str:
    m = p["meta"]
    lines = ["# Bolo Form evaluation report", ""]
    if m["simulated"]:
        lines += ["> **SIMULATED RESULTS (mock provider).** Recognition errors here are injected by a random "
                  "generator. These numbers test the evaluation plumbing only and say nothing about Gnani "
                  "Prisma or Timbre. Do not quote them.", ""]
    lines += [f"- Provider: `{m['provider']}`  |  split: `{m['split']}`  |  personas: {m['personas']}  |  seed: {m['seed']}",
              f"- Generated: {m['generated_at']}  |  conditions: {', '.join(m['conditions'])}", ""]
    for cond, pols in p["results"].items():
        lines += [f"## Condition: {cond}", "",
                  "| Policy | n fields | First-pass acc | Final acc | Silent-error rate (95% CI) | Caught | Turns/form | Confirms/form | Typed fallback |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for pol, r in pols.items():
            lo, hi = r["silent_error_rate_ci95"]
            lines.append(f"| {pol} | {r['n_fields']} | {r['first_pass_acc']:.1%} | {r['final_acc']:.1%} | "
                         f"{r['silent_error_rate']:.1%} ({lo:.1%}-{hi:.1%}) | {r['errors_caught']} | "
                         f"{r['turns_per_form']} | {r['confirms_per_form']} | {r['typed_fallback_rate']:.1%} |")
        lines.append("")
    lines += ["## Worst adaptive-policy failures (synthetic data)", ""]
    for w in p["worst_adaptive_failures"][:10] or []:
        lines.append(f"- [{w['condition']}] `{w['key']}` truth={w['truth']!r} got={w['got']!r} heard={w['heard']!r} "
                     f"status={w['status']} silent={w['silent']}")
    if not p["worst_adaptive_failures"]:
        lines.append("- none in this run")
    lines += ["", "## Limits (read before quoting any number)", "",
              "- Test speech is generated by TTS, which is cleaner and more uniform than real human speech.",
              "- One synthetic voice does not cover Telugu dialects or real speakers.",
              "- The simulated user always notices a wrong read-back and always understands yes/no.",
              "- Noise is synthetic (pink noise); the phone-line condition is a simple band-limit + 8 kHz + mu-law model.",
              "- Thresholds are defaults; tune on `--split dev`, report `--split test`.",
              "- Small n gives wide confidence intervals. Look at the intervals, not just the point values.", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    raise SystemExit(main())
